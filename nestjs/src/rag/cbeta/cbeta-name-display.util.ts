export type NameDisplayLang = 'vi' | 'en' | 'zh';

/** One list line: localized name + Hán in parentheses when mapped. */
export function formatMasterDisplayName(
  nameZh: string,
  lang: NameDisplayLang,
): string {
  const zh = (nameZh || '').trim();
  if (!zh) return '';
  if (lang === 'zh') return zh;
  const mapped = lang === 'en' ? NAME_EN[zh] : NAME_VI[zh];
  if (!mapped) return zh;
  return `${mapped} (${zh})`;
}
